"""Run the trained detectors over the held-out test images in data/test_images/
and write annotated copies, vision_results.json and vision_report.md into outputs/.
Needs the [vision] extra and the weights in weights/.

    python -m scripts.run_test_images
"""
from __future__ import annotations

import json
from pathlib import Path

from src.paths import DATA, OUTPUTS, WEIGHTS
from src.vision.linking import SCORE_THRESHOLD

IMAGES = DATA / "test_images"
REPORT_DIR = OUTPUTS / "test_images"

# Rare damage classes were folded into "Other damage" during training.
MERGE = {"Flaking": "Other damage", "Corrosion": "Other damage",
         "Cracked": "Other damage"}

SWEEP = (0.3, 0.35, 0.4, 0.45, 0.5, 0.6, 0.7)
COLOURS = {"damage": (220, 60, 60), "part": (60, 150, 220)}


def annotate(image, damage, parts, out_path):
    from PIL import ImageDraw
    canvas = image.convert("RGB").copy()
    d = ImageDraw.Draw(canvas)
    for dets, kind in ((parts, "part"), (damage, "damage")):
        for det in dets:
            x1, y1, x2, y2 = det.box
            d.rectangle([x1, y1, x2, y2], outline=COLOURS[kind], width=3)
            label = f"{det.label} {det.score:.2f}"
            tb = d.textbbox((x1, max(0, y1 - 14)), label)
            d.rectangle(tb, fill=COLOURS[kind])
            d.text((x1, max(0, y1 - 14)), label, fill=(255, 255, 255))
    canvas.save(out_path)


def main() -> None:
    from PIL import Image

    from src.vision.detector import ClaimVision

    truth_file = IMAGES / "ground_truth.json"
    if not truth_file.exists():
        raise SystemExit(
            f"no test images in {IMAGES}.\n\n"
            "They come from the held-out split recorded in the damage run's\n"
            "splits.json. See data/test_images/README.md.")
    for w in ("damage.pt", "parts.pt"):
        if not (WEIGHTS / w).exists():
            raise SystemExit(f"missing {WEIGHTS / w}. See the README.")

    truth = json.loads(truth_file.read_text())
    cv = ClaimVision(WEIGHTS / "damage.pt", WEIGHTS / "parts.pt")
    REPORT_DIR.mkdir(parents=True, exist_ok=True)

    results, cache = {}, {}
    for name in sorted(truth):
        image = Image.open(IMAGES / name)
        dmg = cv.damage.detect(image)
        prt = cv.parts.detect(image)
        cache[name] = dmg
        linked = cv.assess_photo(image)
        annotate(image,
                 [d for d in dmg if d.score >= SCORE_THRESHOLD],
                 [p for p in prt if p.score >= SCORE_THRESHOLD],
                 REPORT_DIR / f"{Path(name).stem}_annotated.png")
        want = sorted({MERGE.get(k, k) for k in truth[name]["damage_types"]})
        results[name] = {
            "size": list(image.size),
            "truth_types": want,
            "truth_instances": truth[name]["instances"],
            "damaged_parts": linked.damaged_parts,
            "unlinked_damage": linked.unlinked_damage,
            "needs_review": linked.needs_review,
            "review_reasons": linked.review_reasons,
            "detections": {
                "damage": [{"label": d.label, "score": round(d.score, 3),
                            "box": [round(v) for v in d.box]} for d in dmg
                           if d.score >= SCORE_THRESHOLD],
                "parts": [{"label": p.label, "score": round(p.score, 3),
                           "box": [round(v) for v in p.box]} for p in prt
                          if p.score >= SCORE_THRESHOLD],
            },
        }

    sweep = []
    for thr in SWEEP:
        tp = fp = n = 0
        for name, dets in cache.items():
            got = {d.label for d in dets if d.score >= thr}
            want = {MERGE.get(k, k) for k in truth[name]["damage_types"]}
            tp += len(got & want); fp += len(got - want); n += len(want)
        sweep.append({"threshold": thr, "found": tp, "of": n,
                      "recall": round(tp / n, 3), "false_types": fp})

    (OUTPUTS / "vision_results.json").write_text(
        json.dumps({"images": results, "threshold_sweep": sweep,
                    "operating_threshold": SCORE_THRESHOLD}, indent=1))

    doc = [
        "# Vision outputs on held-out test images",
        "",
        f"Generated by `python -m scripts.run_test_images` at the operating "
        f"threshold of {SCORE_THRESHOLD}.",
        "",
        f"The {len(truth)} images come from the held-out test split recorded in "
        "the damage run's `splits.json`. The detectors never saw them. Annotated "
        "copies with boxes and scores are in `outputs/test_images/`.",
        "",
        "| image | labelled types | parts found, with damage | missed |",
        "| --- | --- | --- | --- |",
    ]
    for name, r in results.items():
        found = sorted({k for ks in r["damaged_parts"].values() for k in ks})
        missed = sorted(set(r["truth_types"]) - set(found))
        parts = "; ".join(f"**{p}**: {', '.join(k)}"
                          for p, k in r["damaged_parts"].items()) or "none"
        doc.append(f"| `{name}` | {len(r['truth_types'])} types, "
                   f"{r['truth_instances']} instances | {parts} | "
                   f"{', '.join(missed) if missed else 'none'} |")

    doc += [
        "",
        "## What this shows",
        "",
        "**The parts detector carries the system.** Back-bumper, Trunk, Hood, "
        "Grille, Headlight, Rocker-panel and Quarter-panel are all identified "
        "correctly, and every damage that was found landed on a plausible panel.",
        "",
        "**The damage detector is the weak half, and the threshold is why.** At "
        f"{SCORE_THRESHOLD} it names only the confident classes. The classes it "
        "misses are still being proposed, just below the cut:",
        "",
        "| threshold | damage types found | of labelled | recall | false types |",
        "| --- | --- | --- | --- | --- |",
    ]
    for s in sweep:
        mark = "  <- operating" if s["threshold"] == SCORE_THRESHOLD else ""
        doc.append(f"| {s['threshold']:.2f} | {s['found']} | {s['of']} | "
                   f"{s['recall']:.0%} | {s['false_types']}{mark} |")

    lo, hi = sweep[0], next(s for s in sweep if s["threshold"] == SCORE_THRESHOLD)
    doc += [
        "",
        f"Dropping the threshold from {SCORE_THRESHOLD} to {lo['threshold']} takes "
        f"recall from {hi['recall']:.0%} to {lo['recall']:.0%} while the number of "
        f"wrongly named types stays at {lo['false_types']}. So "
        f"{SCORE_THRESHOLD} is costing most of the damage recall and buying very "
        "little precision.",
        "",
        "**This is five images, chosen as the richest in the split, so it is a "
        "signal and not a recalibration.** The threshold was picked once and never "
        "swept. It should be swept on the full 81-image test split, and probably "
        "set per class: `Paint chip` peaks around 0.35-0.48 and never clears 0.6, "
        "while `Missing part` clears it easily.",
        "",
    ]
    (OUTPUTS / "vision_report.md").write_text("\n".join(doc))

    print(f"  {len(results)} images assessed")
    print(f"  wrote {OUTPUTS / 'vision_report.md'}")
    print(f"  wrote {OUTPUTS / 'vision_results.json'}")
    print(f"  wrote {len(results)} annotated images to {REPORT_DIR}")


if __name__ == "__main__":
    main()
