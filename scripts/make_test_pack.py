"""Write the sample test pack: worked assessments a reviewer can read without
running anything. Produces outputs/test_pack.md and outputs/assessments.json.

    python -m scripts.make_test_pack
"""
from __future__ import annotations

import json

from src.claim.pipeline import assess_claim, load_policy
from src.env import load_env
from src.paths import OUTPUTS, SAMPLE_POLICIES, TEST_CLAIMS

SHOWCASE = ["APPROVED", "PARTIALLY_APPROVED", "REJECTED", "NEEDS_MANUAL_REVIEW"]


def assess_all(reader: str = "baseline") -> list[dict]:
    claims = json.loads(TEST_CLAIMS.read_text())
    cache: dict[str, dict] = {}
    out = []
    for c in claims:
        pdf = SAMPLE_POLICIES / f"{c['policy']}.pdf"
        cache.setdefault(c["policy"], load_policy(pdf))
        r = assess_claim(pdf, c["incident"], c["damaged_parts"],
                         reader=reader, policy=cache[c["policy"]], claim_id=c["id"])
        out.append({"claim": c, "result": r})
    return out


def render(entry: dict) -> str:
    c, r = entry["claim"], entry["result"]
    lines = [
        f"### {c['id']} — {r['outcome'].replace('_', ' ').title()}",
        "",
        f"**Policy** `{c['policy']}` ({r['policy']['cover_type']}, "
        f"{r['policy']['period_from']} to {r['policy']['period_to']})",
        "",
        f"**Incident** {c['incident'].get('date', 'no date given')} — "
        f"{c['incident'].get('cause', 'no cause given')}. "
        f"{c['incident'].get('description', '')}".rstrip(),
        "",
        f"**Damaged parts** {', '.join(c['damaged_parts']) if c['damaged_parts'] else 'none given'}",
        "",
        f"**Decision** `{r['outcome']}`, decided at the *{r['stage'] or 'final'}* stage",
        "",
    ]
    if r["reasons"]:
        lines += ["**Why**", ""] + [f"- {x}" for x in r["reasons"]] + [""]
    if r["clauses_cited"]:
        lines += ["**Clauses it rests on**", ""]
        for cid, text in r["clauses_cited"].items():
            lines.append(f"- `{cid}` — \"{' '.join(text.split())[:150]}\"")
        lines.append("")
    agree = "matches" if r["outcome"] == c["expected_outcome"] else \
        f"**differs from** the label `{c['expected_outcome']}`"
    lines += [f"*Labelled `{c['expected_outcome']}`; the system {agree}.*", ""]
    return "\n".join(lines)


def main() -> None:
    load_env()
    OUTPUTS.mkdir(exist_ok=True)
    entries = assess_all()

    (OUTPUTS / "assessments.json").write_text(
        json.dumps(entries, indent=1, default=str))

    picked, seen = [], set()
    for e in entries:
        o = e["result"]["outcome"]
        if o in SHOWCASE and o not in seen:
            seen.add(o)
            picked.append(e)

    n_ok = sum(e["result"]["outcome"] == e["claim"]["expected_outcome"]
               for e in entries)
    doc = [
        "# Sample test pack",
        "",
        "Generated by `python -m scripts.make_test_pack`. Every decision here came "
        "from running the system, not from hand-writing an example.",
        "",
        f"**Inputs.** The eight policies in `data/sample_policies/` and the "
        f"{len(entries)} labelled claims in `data/test_claims.json`.",
        "",
        f"**Result.** {n_ok} of {len(entries)} match their label "
        f"({n_ok / len(entries):.0%}) using the keyword baseline reader, which "
        f"needs no API key. Every claim's full decision, including the findings "
        f"and their citations, is in `outputs/assessments.json`.",
        "",
        "A worked example of each outcome follows.",
        "",
    ]
    for e in picked:
        doc.append(render(e))

    wrong = [e for e in entries
             if e["result"]["outcome"] != e["claim"]["expected_outcome"]]
    if wrong:
        doc += ["## Where it disagrees with the labels", "",
                "Kept in, not hidden. These are the two cases the write-up "
                "discusses: the baseline cannot follow a cross-reference, and it "
                "matched a windshield to a body-panel depreciation rate.", ""]
        for e in wrong:
            doc.append(render(e))

    doc += ["## Test images", "",
            "The vision stage was validated on the held-out split of the Kaggle "
            "car-damage datasets, in `notebooks/`. Those images are not "
            "redistributed here. To run the detectors over your own photos, put "
            "them in `data/test_images/` and see `data/test_images/README.md`.", ""]

    (OUTPUTS / "test_pack.md").write_text("\n".join(doc))
    print(f"  {len(entries)} claims assessed, {n_ok} matching their label")
    print(f"  wrote {OUTPUTS / 'test_pack.md'}")
    print(f"  wrote {OUTPUTS / 'assessments.json'}")


if __name__ == "__main__":
    main()
